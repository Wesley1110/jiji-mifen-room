import assert from 'node:assert/strict';
import {createNavigation} from '../navigation.js';
let bedroom=0,entry=0;
const nav=createNavigation(()=>bedroom,()=>entry);
const move=(p,d)=>{nav.move(p,d);return p;};
let p={x:-3.55,y:1.65,z:9.6};
move(p,{x:0,y:0,z:3});assert(p.z<10.05,'closed bedroom door stops movement');
bedroom=1.54;p={x:-3.55,y:1.65,z:9.6};move(p,{x:0,y:0,z:3});assert(p.z>12.5,'bedroom still connects to the hall');
p={x:-7.15,y:1.65,z:18.6};move(p,{x:0,y:0,z:3});assert(p.z<=19.18,'closed front door stops the camera before the exterior');
entry=1.63;p={x:-7.15,y:1.65,z:18.6};move(p,{x:0,y:0,z:5});assert(p.z>23.5,'open door leads onto the porch and garden');
move(p,{x:0,y:0,z:-5});assert(p.z<18.7,'outside-to-inside return uses the same opening');
p={x:0,y:1.65,z:18.6};move(p,{x:0,y:0,z:5});assert(p.z<=19.18,'garden window is not a walk-through opening');
p={x:-8.7,y:1.65,z:15.73};move(p,{x:-4,y:0,z:0});assert(p.x< -12.6,'expanded reading arch is connected');
p={x:-8.7,y:1.65,z:18.05};move(p,{x:-3,y:0,z:0});assert(p.x>=-8.95,'solid wall above arch remains blocking');
p={x:-8.7,y:4.15,z:15.73};move(p,{x:-3,y:0,z:0});assert(p.x>=-8.95,'arch spandrel blocks high flight');
assert.equal(nav.canCloseEntry({x:-7.15,y:1.65,z:19.53}),false,'front door never closes through the viewer');
assert.equal(nav.canCloseEntry({x:-7.15,y:1.65,z:22}),true,'door may close once the viewer clears it');
p={x:-7.15,y:1.65,z:22};move(p,{x:0,y:0,z:30});assert(p.z<=28.4,'fast movement stays within the garden');
assert.equal(nav.allowed({x:-15.4,y:1.2,z:15.8}),false,'camera cannot enter the upholstered bench');
assert.equal(nav.allowed({x:-15.4,y:2.4,z:15.8}),true,'free flight above the bench remains possible');
p={x:-7.15,y:1.65,z:21.9};move(p,{x:0,y:0,z:6.2});assert(p.z>28.0,'central garden path stays open past all four carrot beds');
p={x:-7.15,y:1.65,z:25.23};move(p,{x:-6,y:0,z:0});assert(p.x< -13,'cross aisle allows walking between the two left beds');
move(p,{x:12,y:0,z:0});assert(p.x> -1.2,'cross aisle also reaches the two right beds');
p={x:-7.15,y:1.65,z:23.78};move(p,{x:-6,y:0,z:0});assert(p.x> -8.75,'walking toward a planted bed stops at its timber edge');
assert.equal(nav.allowed({x:-10.8,y:1.65,z:23.78}),false,'walking cannot clip through a planted carrot bed');
assert.equal(nav.allowed({x:-10.8,y:2.2,z:23.78}),true,'visitors can still fly over the carrot beds');
console.log('House navigation: doors, return path, arch, glazing, furniture, garden aisles, planted beds, safe closing and fast movement passed.');
